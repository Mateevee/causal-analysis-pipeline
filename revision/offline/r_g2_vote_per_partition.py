"""
Majority vote of the five baselines split into development and held-out (Table S8.1 per partition).

Origin
  External check pasted by the author on 2026-11-24 ("Majority vote per partition. Table S8.1 still has only
  the 90 scenarios, and the claim remains in three places (gap G2, Sections V-A and VI-A). It is the same pattern as the lag").
  Same pattern as item 58 of NOTAS_FINAIS (lag window per partition).

Design, fixed before looking at the result
  - reuses `generators/paper_numbers.py` without changing it: `load()` and `ensemble()`, the same rules (strict
    majority, at least half, union, intersection), the same pair sets and the same tests (sign and two-sided Wilcoxon);
  - partition by the HELDOUT list of paper_numbers itself (`group_of(s) in HELDOUT`);
  - both windows (10 and 24);
  - check: the sum of the two partitions must reproduce the 90 of Table S8.1 (tau 10: strict majority 0.432,
    pipeline 65/14/11); if it does not, the report says so and nothing goes into the text;
  - every number goes into the report, favourable or not.

Output: Results_Revisao/r_g2_voto_por_particao/RELATORIO.md
Usage:  python revision/offline/r_g2_vote_per_partition.py
"""
from __future__ import annotations

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(ROOT, "generators"))
os.chdir(ROOT)

import paper_numbers as pn  # noqa: E402

OUTPUT = os.path.join(ROOT, "Results_Revisao", "r_g2_voto_por_particao")
os.makedirs(OUTPUT, exist_ok=True)

lines = ["# Majority vote of the five baselines per partition (Table S8.1)", "",
         "Generated by `revision/offline/r_g2_vote_per_partition.py`, which calls `load()` and `ensemble()` from "
         "`generators/paper_numbers.py` without changing it, once per partition.", ""]
for window in pn.SOURCES:
    pn.WINDOW = window
    rows, _prov = pn.load()
    parts = [("All (check against Table S8.1)", lambda s: True),
             ("Development", lambda s: pn.group_of(s) not in pn.HELDOUT),
             ("Held-out", lambda s: pn.group_of(s) in pn.HELDOUT)]
    for name, keep in parts:
        sub = {s: mm for s, mm in rows.items() if keep(s)}
        R = pn.Rep()
        pn.ensemble(R, sub)
        lines += [f"## tau_max = {window} -- {name}", ""] + R.lines + [""]

with open(os.path.join(OUTPUT, "RELATORIO.md"), "w", encoding="utf-8", newline="\r\n") as f:
    f.write("\n".join(lines) + "\n")
print("\n".join(lines))
