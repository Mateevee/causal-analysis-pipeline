"""
Union of the five baselines on the held-out set: precision, recall, fraction of pairs accepted and position relative to the trivial floor.

Origin
  External check pasted by the author on 2026-11-24, after item 60 of NOTAS_FINAIS: hypothesis (not checked) that
  the union ties with the pipeline on the held-out set because it accepts many pairs on weak-signal data and comes close
  to the trivial floor (declaring every pair causal), like the tuned CUTS+ and VARLiNGAM.

Design, fixed before looking at the result
  - same pair sets and same union rule as `generators/paper_numbers.py` (`ensemble`): each baseline that
    ran votes for the ordered entity pair if it reports at least one significant link of it; the union accepts the pair with
    one vote; the logic is copied line by line and checked: the mean F1 of the union per partition must reproduce
    panel (3) of S8.1 (tau 10: 0.265 on held-out; 0.541 on development), otherwise nothing goes into the text;
  - per scenario: TP, FP, FN, precision, recall, fraction of the pair universe accepted, trivial floor 2p/(1+p) with
    p = n_causal / n_universe (the paper_numbers definition), F1 - floor;
  - the same for the pipeline, on the same scenarios;
  - summary per partition: means, how many scenarios below the floor, how many with F1 equal to the floor (|diff| < 0.005),
    mean precision, mean accepted fraction, and the pipeline x union sign test already reported (for reference);
  - both windows; every number goes into the report, favourable or not.

Recorded deviation (2026-11-24, after the first run)
  The 'below the floor' count with the 0.005 band gave 22 for the pipeline on the held-out set, against the paper's 23,
  which use the rule of `paper_numbers.shortfall`: F1 (rounded to 4 decimal places) < floor - 1e-9. Added the column with
  the paper's rule, which becomes the reference; the 0.005 band is kept as information.

Output: Results_Revisao/r_g2_voto_por_particao/UNIAO_PISO.md
Usage:  python revision/offline/r_g2_floor_union.py
"""
from __future__ import annotations

import os
import sys

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(ROOT, "generators"))
os.chdir(ROOT)

import paper_numbers as pn  # noqa: E402

OUTPUT = os.path.join(ROOT, "Results_Revisao", "r_g2_voto_por_particao")
os.makedirs(OUTPUT, exist_ok=True)
EPS_FLOOR = 0.005


def per_scenario(rows):
    P = pn.PIPELINE_MODEL
    out = []
    for scen, mm in sorted(rows.items()):
        if P not in mm:
            continue
        gt = pd.read_csv(os.path.join(pn.run_of(rows, scen), scen, "ground_truth.csv"))
        gt["pos"] = gt["causal_gt"].astype(str).str.lower().isin(["true", "1"])
        g = gt.groupby([gt["source_entity"].astype(str), gt["target_entity"].astype(str)])["pos"].any()
        T, U = set(g[g].index), set(g.index)
        sets = {}
        for m, _lab in pn.BASELINES:
            if m not in mm:
                continue
            run, name = mm[m]["run"].rsplit(":", 1)
            d = pd.read_csv(os.path.join(run, scen, name, "results.csv"), low_memory=False)
            if "significant" in d.columns:
                d = d[d["significant"].astype(str) == "True"]
            sets[m] = set(zip(d["source_entity"].astype(str), d["target_entity"].astype(str))) & U
        S = set().union(*sets.values()) if sets else set()
        tp, fp, fn = len(S & T), len(S - T), len(T - S)
        r = mm[P]
        p = r["n_causal"] / r["n_universe"]
        floor = 2 * p / (1 + p)
        ptp, pfp, pfn = r["tp"], r["fp"], r["fn"]
        out.append(dict(
            cenario=scen, heldout=pn.group_of(scen) in pn.HELDOUT, piso=floor, n_universo=len(U), n_causal=len(T),
            u_f1=round(pn.f1(tp, fp, fn), 4), u_prec=tp / (tp + fp) if tp + fp else np.nan,
            u_rec=tp / (tp + fn) if tp + fn else np.nan, u_frac=len(S) / len(U) if U else np.nan,
            p_f1=round(pn.f1(ptp, pfp, pfn), 4), p_prec=ptp / (ptp + pfp) if ptp + pfp else np.nan,
            p_rec=ptp / (ptp + pfn) if ptp + pfn else np.nan, p_frac=(ptp + pfp) / len(U) if U else np.nan))
    return pd.DataFrame(out)


lines = ["# Union of the five baselines relative to the trivial floor, per partition", "",
         "Generated by `revision/offline/r_g2_floor_union.py` (design in the script header).", ""]
for window in pn.SOURCES:
    pn.WINDOW = window
    rows, _ = pn.load()
    D = per_scenario(rows)
    D.to_csv(os.path.join(OUTPUT, f"uniao_piso_tau{window}.csv"), index=False)
    for name, X in [("Development", D[~D.heldout]), ("Held-out", D[D.heldout])]:
        lines += [f"## tau_max = {window} -- {name} ({len(X)} scenarios)", ""]
        lines += ["| Method | Mean F1 | Mean precision | Mean recall | Fraction of pairs accepted (mean) | "
                  "Below the floor (paper's rule) | Below the floor by more than 0.005 | Equal to the floor (diff < 0.005) | F1 - floor (mean) |",
                  "|---|---|---|---|---|---|---|---|---|"]
        for tag, pre in [("Pipeline", "p_"), ("Union", "u_")]:
            diff = X[pre + "f1"] - X["piso"]
            lines.append(f"| {tag} | {X[pre + 'f1'].mean():.3f} | {X[pre + 'prec'].mean():.3f} | "
                         f"{X[pre + 'rec'].mean():.3f} | {X[pre + 'frac'].mean():.3f} | "
                         f"{int((X[pre + 'f1'] < X['piso'] - 1e-9).sum())} | {int((diff < -EPS_FLOOR).sum())} | "
                         f"{int((diff.abs() < EPS_FLOOR).sum())} | {diff.mean():+.3f} |")
        lines.append(f"| Trivial floor | {X['piso'].mean():.3f} | | | 1.000 | | | | |")
        lines.append("")
        if name == "Held-out":
            lines += ["Per scenario (held-out): F1 of the union / of the pipeline / floor; fraction accepted by the union; precision of the union",
                      ""]
            for _, r in X.iterrows():
                lines.append(f"- {r.cenario}: {r.u_f1:.3f} / {r.p_f1:.3f} / {r.piso:.3f}; {r.u_frac:.2f}; "
                             f"{r.u_prec:.3f}")
            lines.append("")

with open(os.path.join(OUTPUT, "UNIAO_PISO.md"), "w", encoding="utf-8", newline="\r\n") as f:
    f.write("\n".join(lines) + "\n")
print("\n".join(lines))
