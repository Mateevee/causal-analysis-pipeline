# Lag-sensitive scoring (G1) on the synthetic VAR scenarios, the only ones with the
# true lag recorded: the unit is the link (source, target, lag). A true pair
# reported at another lag counts as one false positive and one false negative;
# methods that report several lags per pair have each lag counted.
out.append("## 1b. Lag recovery (synthetic VAR scenarios)\n")
METHODS = {"Pipeline": "patch", **BASELINES}
LAG_CUT = 4   # largest true lag of the generator (checked below)


def _truth_lags(folder):
    txt = open(os.path.join(folder, "scenario_params.txt"), encoding="utf-8").read()
    edges = ast.literal_eval(txt.split("causal_edges             :")[1].split("\n")[0].strip())
    return {(e["source"], e["target"]): e["lag"] for e in edges}


def _links(path):
    d = pd.read_csv(path)
    d = d[d["significant"].astype(str) == "True"]
    return {(r.source_entity, r.target_entity, int(r.lag)) for r in d.itertuples()
            if r.source_entity != r.target_entity}


def _lag_score(items):
    s = dict(true=0, pair=0, at_lag=0, tp=0, fp=0, fn=0, fp_pairs=0, fp_links=0, fp_long=0, short=0, long=0)
    for T, P in items:
        pairs = {(a, b) for a, b, _ in P}
        TL = {(a, b, l) for (a, b), l in T.items()}
        s["true"] += len(T)
        for k, l in T.items():
            if k in pairs:
                lags = [x for a, b, x in P if (a, b) == k]
                s["pair"] += 1
                if l in lags:
                    s["at_lag"] += 1
                elif max(lags) < l:
                    s["short"] += 1
                else:
                    s["long"] += 1
        s["tp"] += len(P & TL); s["fp"] += len(P - TL); s["fn"] += len(TL - P)
        s["fp_pairs"] += len(pairs - set(T))
        off = [x for a, b, x in P if (a, b) not in T]
        s["fp_links"] += len(off); s["fp_long"] += sum(x > LAG_CUT for x in off)
    s["prec"] = s["tp"] / max(s["tp"] + s["fp"], 1)
    s["rec"] = s["tp"] / max(s["tp"] + s["fn"], 1)
    s["f1"] = 2 * s["tp"] / max(2 * s["tp"] + s["fp"] + s["fn"], 1)
    return s


_LAG_HEAD = ("| {} | True links recovered (any lag) | At the true lag | Lag too short / too long | "
             "Link-level precision | Link-level recall | Link-level F1 | False-positive pairs | "
             f"Links on those pairs at lag > {LAG_CUT} |")


def _lag_row(name, s):
    return (f"| {name} | {s['pair']}/{s['true']} | {s['at_lag']} | {s['short']} / {s['long']} | {s['prec']:.3f} | "
            f"{s['rec']:.3f} | {s['f1']:.3f} | {s['fp_pairs']} | {s['fp_long']} of {s['fp_links']} |")


