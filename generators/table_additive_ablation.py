"""
Generates the tables of the additive and subtractive ablation (Section 5.4, Tables 3a-3d;
Table S24) from Results_Ablation (main_ablation_patch.py), at both
windows. Also checks that step 7 (full pipeline) reproduces the official
run on each scenario.

Steps 1-7: additive (one component at a time, starting from the isolated DML).
Steps 8-10: full pipeline minus one regime-dependent component.

Output: Table_Additive_Ablation.md
"""
import csv
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import origins as O  # noqa: E402

ABL = O.require("ABLATION_DIR")
OUT = O.out("Table_Additive_Ablation.md")

WINDOWS = [("10", "tau10", "patch_tau10"), ("24", "tau24", "patch")]
SCENARIOS = [
    ("benchmark_synthetic_var_3_seed33", "`benchmark_synthetic_var_3` (seed 33; 17 ground-truth links)"),
    ("benchmark_tigramite_large_mixed_seed11",
     "`benchmark_tigramite_large_mixed` (seed 11; 4 entity-pair-level ground-truth links)"),
    ("benchmark_lorenz96_K10_seed1", "`benchmark_lorenz96_K10` (seed 1; 30 ground-truth links)"),
    ("benchmark_causaltime_medical_sample0", "`benchmark_causaltime_medical` (sample 0; 133 ground-truth links)"),
]
STEPS = [
    ("1_isolated_dml", "1. DML alone", "Bayesian Ridge"),
    ("2_plus_property_filter", "2. + active-property filter", "Bayesian Ridge"),
    ("3_prefilter_with_lag_penalty", "3. + lag penalization", "Bayesian Ridge"),
    ("4_plus_auxiliary_cascade", "4. + auxiliary-model cascade (isolated)", "cascade"),
    ("5_plus_causal_penalty", "5. + effect filtering (isolated)", "Bayesian Ridge"),
    ("6_plus_structural_optimization", "6. + structural adjustment (Stage 8, isolated)", "Bayesian Ridge"),
    ("7_full_pipeline", "**Full pipeline**", "cascade"),
    ("8_full_minus_control_set", "Full pipeline, blanket design throughout", "cascade"),
    ("9_full_minus_predictive", "Full pipeline without the predictive competition", "cascade"),
    ("10_full_minus_coherence_guard", "Full pipeline without the evidence-coherence guard", "cascade"),
]
ADDITIVE = {s[0] for s in STEPS[:7]}


def f1(r):
    tp, fp, fn = int(r["TP"]), int(r["FP"]), int(r["FN"])
    return 0.0 if tp == 0 else 2 * tp / (2 * tp + fp + fn)


def read(path):
    return {r["model"]: r for r in csv.DictReader(open(path, encoding="utf-8"))}


out = ["# Additive and subtractive ablation -- generated by generators/table_additive_ablation.py", ""]
ok_all = True
for w, folder, main_model in WINDOWS:
    for sc, title in SCENARIOS:
        rows = read(os.path.join(ABL, folder, sc, sc, "validation_summary.csv"))
        ref = read(os.path.join(O.find(sc), "validation_summary.csv"))[main_model]
        full = rows["7_full_pipeline"]
        same = (full["TP"], full["FP"], full["FN"]) == (ref["TP"], ref["FP"], ref["FN"])
        ok_all &= same
        best = max(f1(rows[k]) for k in ADDITIVE if rows[k]["status"] == "ok")
        out += [f"## tau{w} | {sc}", "",
                f"<!-- {title}; step 7 {'reproduces' if same else 'DOES NOT REPRODUCE'} the official run "
                f"({ref['TP']}/{ref['FP']}) -->", "",
                "| Step | DML model | F1 (TP/FP) |", "|---|---|---|"]
        for key, label, model in STEPS:
            r = rows[key]
            cell = f"{f1(r):.4f} ({r['TP']}/{r['FP']})"
            if key in ADDITIVE and abs(f1(r) - best) < 1e-9 and best > 0:
                cell = f"**{cell}**"
            out.append(f"| {label} | {model} | {cell} |")
        out.append("")

open(OUT, "w", encoding="utf-8").write("\n".join(out) + "\n")
print("saved to", OUT)
print("step 7 reproduces the official run on every scenario and window:", ok_all)
