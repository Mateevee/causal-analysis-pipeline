"""
Cause of the undercoverage of the Stage 6 intervals on the synthetic VAR scenarios
(Table S9, controls panel).

For each true link reported at the true lag (the same links as in
Table S9, generated by additional_analyses.py), re-estimates theta with the
pipeline's DML (lean design: the target's own past + other parents, source
block; BayesianRidge; K = 3 contiguous blocks) under three control sets:

  candidates      the other candidate parents of the target that the pipeline used
                  (patch*/original.csv) -- must reproduce the reported value;
  candidates+purge  the same controls, with a purge gap of
                  (window + lag) observations between the test block and the
                  training block of the cross-fitting;
  true parents    the other true parents of the target (scenario_params.txt),
                  each one at its lag.

Nothing of the pipeline is re-run besides Stage 6 of these links; the DML engine is
that of Pipeline/dml_engine.py. Writes Table_S9_Controls.md.
"""
import ast
import os
import re
import sys

import numpy as np
import pandas as pd
from sklearn.linear_model import BayesianRidge

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import origins as O  # noqa: E402
sys.path.insert(0, O.REPO)
from Pipeline import dml_engine as E  # noqa: E402

RUN = O.require("MAIN_RUN")
OUT = O.out("Table_S9_Controls.md")
SEEDS = [11, 22, 33, 44, 55]
WINDOWS = [("10", "patch_tau10", 10), ("24", "patch", 24)]
K = 3


def lagged(x, l):
    out = np.full(len(x), np.nan)
    out[l:] = x[:-l]
    return out


def crossfit_purge(T, O, W, gap):
    """Cross-fitting over K contiguous blocks with `gap` observations removed from
    training on each side of the test block (gap = 0 reproduces _run_crossfit)."""
    n = len(T)
    block = max(n // K, 1)
    rT, rO = np.zeros(n), np.zeros(n)
    idx = np.arange(n)
    for f in range(K):
        t0, t1 = f * block, ((f + 1) * block if f < K - 1 else n)
        train = idx[(idx < t0 - gap) | (idx >= t1 + gap)]
        test = idx[t0:t1]
        for y, r in ((T, rT), (O, rO)):
            m = BayesianRidge(max_iter=300, tol=1e-3).fit(W[train], y[train])
            r[test] = y[test] - m.predict(W[test])
    return rT, rO


def estimate(proc, parents_of, own, s, t, lag, gap=None):
    W = E._parent_controls(s, t, lag, proc, parents_of, own, K, True)
    T, O = lagged(proc[s], lag), proc[t].copy()
    ok = ~np.isnan(T) & ~np.isnan(O) & ~np.any(np.isnan(W), axis=1)
    T, O, W = T[ok], O[ok], W[ok]
    if gap is None:
        rT, rO, _ = E._run_crossfit("bayesian_ridge", T, O, W, K)
    else:
        rT, rO = crossfit_purge(T, O, W, gap)
    r = E._compute_theta_and_se(rT, rO, len(T), None)
    return r["effect"], r["se"], W.shape[1]


def links_of_window(model, max_lag):
    rows = []
    for i, sd in enumerate(SEEDS, 1):
        sc = f"benchmark_synthetic_var_{i}_seed{sd}"
        base = os.path.join(RUN, sc)
        txt = open(os.path.join(base, "scenario_params.txt"), encoding="utf-8").read()
        edges = ast.literal_eval(re.search(r"causal_edges\s*:\s*(\[.*\])", txt).group(1))
        src = pd.read_csv(os.path.join(base, "source.csv"))
        col = [c for c in src.columns if c not in ("Date", "Name")][0]
        wide = src.pivot(index="Date", columns="Name", values=col)
        proc = {c: (wide[c].values - wide[c].values.mean()) / wide[c].values.std() for c in wide.columns}
        sdv = src.groupby("Name")[col].std()
        truth = {(e["source"], e["target"]): (int(e["lag"]), e["coef"] * sdv[e["source"]] / sdv[e["target"]])
                 for e in edges}
        true_par, cand = {}, {}
        for e in edges:
            true_par.setdefault(e["target"], []).append((e["source"], int(e["lag"])))
        orig = pd.read_csv(os.path.join(base, model, "original.csv"), skipinitialspace=True,
                           usecols=["source_entity", "target_entity", "lag"])
        for r in orig.itertuples():
            cand.setdefault(r.target_entity, []).append((r.source_entity, int(r.lag)))
        own = {k: E._ar_order_bic(proc[k], max_lag) for k in proc}
        d = pd.read_csv(os.path.join(base, model, "results.csv"))
        d = d[d["significant"].astype(str) == "True"]
        for r in d.itertuples():
            k = (r.source_entity, r.target_entity)
            if k not in truth or int(r.lag) != truth[k][0]:
                continue
            s, t, lag = k[0], k[1], int(r.lag)
            e_c, se_c, k_c = estimate(proc, cand, own, s, t, lag)
            e_p, se_p, _ = estimate(proc, cand, own, s, t, lag, gap=max_lag + lag)
            e_o, se_o, k_o = estimate(proc, true_par, own, s, t, lag)
            others = {p for p in true_par.get(t, []) if p[0] != s}
            extra = [p for p in cand.get(t, []) if p not in others and p[0] not in (s, t)]
            rows.append(dict(scenario=sc, source=s, target=t, lag=lag, ref=truth[k][1],
                             model=r.dml_model_used, rep=r.causal_effect,
                             rep_se=(r.ci_95_upper - r.ci_95_lower) / 3.92,
                             cand=e_c, cand_se=se_c, purge=e_p, purge_se=se_p,
                             oracle=e_o, oracle_se=se_o, n_extra=len(extra)))
    return pd.DataFrame(rows)


def summary(d, est, se):
    sg = np.sign(d.ref)
    z = (d[est] - d.ref) / d[se] * sg
    shrink = (d[est].abs() - d.ref.abs()) / d.ref.abs()
    return dict(cov=(z.abs() < 1.96).mean(), zbias=z.mean(), zsd=z.std(), shrink=shrink.mean(),
                mae=(d[est] - d.ref).abs().mean())


out = ["# Table S9 -- Stage 6 controls and coverage (generated by generators/dml_controls.py)",
       f"Run: `{os.path.basename(RUN)}`; DML engine: `Pipeline/dml_engine.py` "
       "(lean design, BayesianRidge, K = 3).\n"]
for w, model, max_lag in WINDOWS:
    d = links_of_window(model, max_lag)
    br = d[d.model == "bayesian_ridge"]
    out.append(f"## tau_max = {w}\n")
    out.append(f"- True links at the true lag: {len(d)} ({len(br)} reported by BayesianRidge).")
    out.append(f"- Reproduction (BayesianRidge): max |reported theta - re-estimated theta| = "
               f"{(br.rep - br.cand).abs().max():.1e}.")
    out.append(f"- Controls that are not true parents, per link: mean {d.n_extra.mean():.1f}, "
               f"median {d.n_extra.median():.0f}; links with none: {(d.n_extra == 0).sum()}.\n")
    out.append("| Controls | 95% CI coverage | Mean (θ̂ − θ)/SE, sign-adjusted | SD of (θ̂ − θ)/SE "
               "| Mean relative error of \\|θ̂\\| | MAE |")
    out.append("|---|---|---|---|---|---|")
    for lab, est, se in [("As reported", "rep", "rep_se"),
                         ("Candidate parents (re-estimated)", "cand", "cand_se"),
                         ("Candidate parents, purge gap", "purge", "purge_se"),
                         ("True parents", "oracle", "oracle_se")]:
        s = summary(d, est, se)
        out.append(f"| {lab} | {s['cov']:.1%} | {s['zbias']:+.2f} | {s['zsd']:.2f} | "
                   f"{s['shrink']:+.1%} | {s['mae']:.3f} |")
    out.append("")
open(OUT, "w", encoding="utf-8").write("\n".join(out) + "\n")
print(f"written {OUT}")
