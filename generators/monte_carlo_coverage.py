"""
Item 3, complement -- coverage over repeated samples.

The 48 links of Table S9 (panel 7) come from 3 seeds per SCM, and the same
seed produces equal or similar noise in different SCMs, so the 79% coverage
rests on few independent realizations. Here every SCM is simulated again with
R seeds the run did not use (same generator and same arguments as
Data/tigramite_scm.py: T = 300, transient_fraction = 0.2) and every true link
is estimated by the pipeline's DML (Bayesian ridge, K = 3 contiguous blocks,
HAC standard error of Pipeline/dml_engine.py) with the reference's controls
(Y_{t-1} only). The reference is the same as in Table_S9_Tigramite_Controls.md.

If coverage over repeated samples is nominal, the 79% is sampling noise from
few correlated realizations; if it is not, the standard error is too short for
that quantity even with the reference's controls.

Usage (after dml_controls_tigramite.py, whose links it reads):
    python generators/monte_carlo_coverage.py
"""
import os
import sys

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import dml_controls_tigramite as D  # noqa: E402

E, TG, toys = D.E, D.TG, D.toys
R = 300
SEEDS_MC = range(1001, 1001 + R)
T_POINTS, TRANSIENT, K = 300, 0.2, 3


def theta_y1(x, y, lag):
    """DML with W = Y_{t-1}, as in D.dml(..., W_y1) (checked in main)."""
    T, O, W = E._lagged(x, lag), y.copy(), E._lagged(y, 1).reshape(-1, 1)
    ok = ~np.isnan(T) & ~np.isnan(O) & ~np.any(np.isnan(W), axis=1)
    rT, rO, _ = E._run_crossfit("bayesian_ridge", T[ok], O[ok], W[ok], K)
    r = E._compute_theta_and_se(rT, rO, int(ok.sum()), None)
    return r["effect"], r["se"]


def zscore(v):
    return (v - v.mean()) / v.std()


def main():
    ref, _ = D.references()
    # check: theta_y1 reproduces the br_y1 column of links_tau10.csv
    lk = pd.read_csv(D.O.out("tigramite_links_tau10.csv"))
    diff = []
    for r in lk.itertuples():
        sc = r.scenario.replace("benchmark_tigramite_", "").rsplit("_seed", 1)[0]
        sd = int(r.scenario.rsplit("seed", 1)[1])
        sdef = TG._BENCHMARK_SCENARIO_DEFINITIONS[sc]
        data, _ = toys.structural_causal_process(links=sdef["links"], T=T_POINTS, seed=sd,
                                                 transient_fraction=TRANSIENT)
        npr = sdef["n_properties"]
        idx = lambda k: int(k.split("__")[0].split("_")[1]) * npr + int(k.split("__")[1].split("_")[1])  # noqa: E731
        th, _ = theta_y1(zscore(data[:, idx(r.source)]), zscore(data[:, idx(r.target)]), r.lag)
        diff.append(abs(th - r.br_y1))
    print(f"check against links_tau10.csv: max |dtheta| = {max(diff):.1e}")

    rows = []
    for sc, sdef in TG._BENCHMARK_SCENARIO_DEFINITIONS.items():
        npr = sdef["n_properties"]
        for sd in SEEDS_MC:
            data, bad = toys.structural_causal_process(links=sdef["links"], T=T_POINTS, seed=sd,
                                                       transient_fraction=TRANSIENT)
            if bad:
                continue
            for tgt, par in sdef["links"].items():
                for (s, tau), _, fn in par:
                    if s == tgt:
                        continue
                    tau = abs(tau)
                    name = lambda v: D.key(f"ENT_{v // npr}", f"F_{v % npr}")  # noqa: E731
                    rf = ref[(sc, name(s), name(tgt))]
                    x, y = data[:, s], data[:, tgt]
                    th, se = theta_y1(zscore(x), zscore(y), tau)
                    rows.append(dict(scm=sc, seed=sd, link=f"{name(s)}->{name(tgt)}", form=D.FORM[rf["form"]],
                                     ref=rf["b"] * x.std() / y.std(), theta=th, se=se))
    d = pd.DataFrame(rows)
    d["z"] = (d.theta - d.ref) / d.se * np.sign(d.ref)
    d["covered"] = d.z.abs() <= 1.96
    d.to_csv(D.O.out("tigramite_monte_carlo_links.csv"), index=False)

    def line(lab, g):
        return (f"| {lab} | {len(g)} | {g.covered.mean():.1%} | {g.z.mean():+.2f} | {g.z.std():.2f} | "
                f"{g.se.mean():.3f} | {f'{g.theta.std():.3f}' if g.link.nunique() == 1 else '—'} |")

    L = ["# Item 3 — Coverage over repeated samples (Monte Carlo)", "",
         f"Generated by `monte_carlo_coverage.py`. {R} new seeds per SCM ({SEEDS_MC.start}–{SEEDS_MC.stop - 1}), "
         f"T = {T_POINTS}, transient_fraction = {TRANSIENT}; the pipeline's DML with Bayesian ridge, K = {K} and controls "
         "= Y_{t−1} only (the reference's). Reference as in `Table_S9_Tigramite_Controls.md`.", "",
         f"Check: this script's estimator reproduces the \"Only Y_{{t−1}}, BR\" column of `links_tau10.csv` "
         f"(max |Δθ| = {max(diff):.1e}).", "",
         "| Group | Estimates | 95% CI coverage | Mean (θ̂ − θ)/SE | SD of (θ̂ − θ)/SE | Mean SE | SD of θ̂ across seeds |",
         "|---|---|---|---|---|---|---|",
         line("All links", d)]
    for f_, g in d.groupby("form", sort=False):
        L.append(line(f_, g))
    L += ["", "By link (SD of θ̂ across seeds vs mean SE: if the SE were correct, the two would be similar):", "",
          "| SCM | Link | Form | Coverage | Mean z | SD of z | Mean SE | SD of θ̂ |", "|---|---|---|---|---|---|---|---|"]
    for (sc, lkn), g in d.groupby(["scm", "link"], sort=False):
        L.append(f"| {sc} | {lkn} | {g.form.iloc[0]} | {g.covered.mean():.1%} | {g.z.mean():+.2f} | {g.z.std():.2f} | "
                 f"{g.se.mean():.3f} | {g.theta.std():.3f} |")
    # The run's 3 seeds are 3 draws of this process. How common is a coverage
    # this low over 3 seeds? The seeds are the unit: within a seed the SCMs share
    # noise, and the links are not independent.
    ps = d.groupby("seed").covered.agg(["sum", "count"])
    rng = np.random.default_rng(0)
    trios = np.array([rng.choice(ps.index.values, 3, replace=False) for _ in range(200_000)])
    cov3 = ps["sum"].values[np.searchsorted(ps.index.values, trios)].sum(1) /         ps["count"].values[np.searchsorted(ps.index.values, trios)].sum(1)
    L += ["", "## The run's three seeds as draws of this process", "",
          f"- Coverage per seed (all the links of the seed): mean {ps['sum'].sum() / ps['count'].sum():.1%}, "
          f"SD across seeds {(ps['sum'] / ps['count']).std():.3f}.",
          f"- Pooled coverage of 3 random seeds: percentiles 1/5/50 = "
          + " / ".join(f"{q:.1%}" for q in np.percentile(cov3, [1, 5, 50])) + "."]
    for w in ["10", "24"]:
        lk = pd.read_csv(D.O.out(f"tigramite_links_tau{w}.csv"))
        lk["seed"] = lk.scenario.str.extract(r"seed(\d+)")[0]
        obs = ((lk.br_y1 - lk.ref).abs() <= 1.96 * lk.br_y1_se)
        per_seed = obs.groupby(lk.seed).agg(["sum", "count"])
        L.append(f"- τ_max = {w}, the run's links with the same controls (Y_{{t−1}} only, BR): coverage {obs.mean():.1%} "
                 f"(per seed: " + ", ".join(f"{k}: {int(r['sum'])}/{int(r['count'])}" for k, r in per_seed.iterrows())
                 + f"); share of the Monte Carlo trios with equal or lower coverage: "
                 f"{(cov3 <= obs.mean() + 1e-9).mean():.1%}.")
    open(D.O.out("Table_S9_Tigramite_MonteCarlo.md"), "w", encoding="utf-8").write("\n".join(L) + "\n")
    print("ok ->", D.O.out("Table_S9_Tigramite_MonteCarlo.md"))


if __name__ == "__main__":
    main()
