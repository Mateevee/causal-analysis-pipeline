"""
Data.netsim
===============================================================================
QUASI-REAL BENCHMARK (SIMULATED) — NETSIM (Smith, Miller, Salimi-Khorshidi,
Webster, Beckmann, Nichols, Ramsey & Woolrich 2011, "Network modelling
methods for FMRI", NeuroImage 54(2):875-891).

Simulated BOLD fMRI time series of interacting brain regions: neural
activity generated by a dynamic causal model on a known directed network,
passed through a haemodynamic (balloon) model and sampled at the scanner
repetition time. One of the most used benchmarks of time-series causal
discovery (TCDF, eSRU, CUTS, CUTS+, the survey of Assaad et al. 2022, ...).

DATA ORIGIN: SIMULATED, not measured.

Simulation `sim3` (the one used by most of that literature): 15 nodes, 50
simulated subjects, 200 time points per subject (TR = 3 s, 10 minutes).
Each subject is its own scenario; the connection pattern is the same for
every subject, the connection strengths differ.

GROUND TRUTH: the connectivity matrix `net` used by the simulator (by
construction). net[i, j] != 0 means node i -> node j (row -> column; the
diagonal holds the self-decay -1 and is ignored). The orientation was
cross-checked against the ground truth distributed with eSRU (Khanna & Tan
2020), whose matrix Gref[target, source] equals net.T for sim3.

CAVEATS
-------------------------------------------------------------------------------
  - Short series (200 points) and a slow, smoothing haemodynamic response:
    the neural lags (tens of milliseconds) are far below the 3 s sampling,
    so the relations are essentially contemporaneous in the sampled data.
    Smith et al. report that lag-based methods perform poorly on these
    simulations.

HOW TO GET THE DATA
-------------------------------------------------------------------------------
Not auto-downloaded. Download `sims.tar.gz` (the 28 simulations, MATLAB
format) from the official page and extract the simN.mat files into
<base_dir>/ (default: env NETSIM_DIR or "./external_data/netsim"):
    page:    https://www.fmrib.ox.ac.uk/datasets/netsim/
    archive: https://www.fmrib.ox.ac.uk/datasets/netsim/sims.tar.gz
The archive (~49 MB) holds sim1.mat ... sim28.mat at its top level, so
    tar -xzf sims.tar.gz -C ./external_data/netsim
(`tar` also ships with Windows 10/11) creates the file read by default:
    ./external_data/netsim/sim3.mat
Each simN.mat holds 'ts' (Nsubjects*Ntimepoints x Nnodes, subjects stacked),
'net' (Nsubjects x Nnodes x Nnodes), 'Nnodes', 'Nsubjects', 'Ntimepoints'.
Requires scipy (scipy.io.loadmat).
"""
from __future__ import annotations

import os
from pathlib import Path
from typing import List, Optional, Sequence, Union

import numpy as np

from .base import array_to_pipeline_format_single_property, register

_BASE_DEFAULT = Path(os.environ.get("NETSIM_DIR", "./external_data/netsim"))


@register("netsim")
def generate_netsim_benchmark_scenarios(
    simulation: str = "sim3",
    subjects: Sequence[int] = (0, 1, 2),
    tr_seconds: float = 3.0,
    base_dir: Optional[Union[str, Path]] = None,
    name_prefix: str = "benchmark_netsim",
) -> List[dict]:
    """
    Loads NetSim subjects as scenarios — see the module docstring for the
    source, the ground truth (the simulator's `net` matrix) and the caveats.

    Parameters
    ----------
    simulation  : which simN.mat to read ("sim3": 15 nodes, 200 points).
    subjects    : indices of the simulated subjects to load, one scenario
                  each (sim3 has 50).
    tr_seconds  : sampling interval used for the synthetic 'Date' column
                  (sim3 was simulated with TR = 3 s). It only labels the
                  time axis; no method reads the interval itself.
    base_dir    : folder with the simN.mat files (default: env NETSIM_DIR or
                  "./external_data/netsim").
    name_prefix : prefix for the name/folder of each generated scenario.
    """
    from scipy.io import loadmat

    root = Path(base_dir) if base_dir is not None else _BASE_DEFAULT
    path = root / f"{simulation}.mat"
    if not path.exists():
        raise FileNotFoundError(
            f"'{path}' not found. Download sims.tar.gz from "
            f"https://www.fmrib.ox.ac.uk/datasets/netsim/ and extract "
            f"{simulation}.mat into '{root}' (or point base_dir= / the "
            f"NETSIM_DIR environment variable)."
        )

    mat = loadmat(str(path))
    n_nodes = int(mat["Nnodes"].squeeze())
    n_subjects = int(mat["Nsubjects"].squeeze())
    n_timepoints = int(mat["Ntimepoints"].squeeze())
    ts, net = mat["ts"], mat["net"]
    if ts.shape != (n_subjects * n_timepoints, n_nodes) or \
            net.shape != (n_subjects, n_nodes, n_nodes):
        raise ValueError(
            f"'{path}' has unexpected shapes ts={ts.shape}, net={net.shape} "
            f"for {n_subjects} subjects x {n_timepoints} points x {n_nodes} nodes."
        )

    entity_names = [f"N{i + 1:02d}" for i in range(n_nodes)]

    scenarios: List[dict] = []
    for subject in subjects:
        if not 0 <= subject < n_subjects:
            raise ValueError(f"subject={subject} outside 0..{n_subjects - 1}.")
        data = np.asarray(ts[subject * n_timepoints:(subject + 1) * n_timepoints],
                          dtype=float)
        gt_matrix = net[subject]
        # net[i, j] != 0: node i -> node j (see the module docstring).
        causal_pair_idx = {(i, j) for i in range(n_nodes) for j in range(n_nodes)
                           if i != j and gt_matrix[i, j] != 0}

        df_long, df_gt = array_to_pipeline_format_single_property(
            data, entity_names, causal_pair_idx,
            start_date="2015-01-01", freq=f"{int(round(tr_seconds * 1000))}ms",
            property_name="BOLD",
        )

        name = f"{name_prefix}_{simulation}_subj{subject}"
        params = {
            "source": "netsim",
            "reference": "Smith et al. 2011, NeuroImage 54(2):875-891",
            "data_file": str(path),
            "simulation": simulation,
            "subject": subject,
            "n_subjects_in_file": n_subjects,
            "n_points": n_timepoints,
            "n_entities": n_nodes,
            "tr_seconds": tr_seconds,
            "n_causal_links": len(causal_pair_idx),
            "simulated": True,
            "ground_truth_type": "connectivity matrix used by the simulator "
                                  "(by construction): dynamic causal model "
                                  "+ haemodynamic response",
        }

        print(f"  [benchmark] {name} loaded — {n_nodes} nodes x "
              f"{n_timepoints} points (TR={tr_seconds:g}s, simulated BOLD) | "
              f"{len(causal_pair_idx)} causal links (simulator's network, "
              f"Smith et al. 2011) | subject {subject} of {n_subjects}")

        scenarios.append({"name": name, "df": df_long, "gt": df_gt,
                          "_scenario": None, "_params": params})

    return scenarios


if __name__ == "__main__":
    for c in generate_netsim_benchmark_scenarios():
        n_edges = int(c["gt"]["causal_gt"].sum())
        print(f"  {c['name']}: df={c['df'].shape}, {n_edges}/{len(c['gt'])} real edges")
